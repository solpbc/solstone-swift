import base64
import os
import sys

def main():
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ir_path = os.path.join(repo_root, "PushCatalog", "contract", "ir.json")
    history_path = os.path.join(repo_root, "PushCatalog", "imported", "history.json")
    output_path = os.path.join(repo_root, "Sources", "Push", "PushCatalogContract.swift")

    with open(ir_path, "rb") as f:
        ir_bytes = f.read()

    with open(history_path, "rb") as f:
        history_bytes = f.read()

    ir_b64 = base64.b64encode(ir_bytes).decode("ascii")
    history_b64 = base64.b64encode(history_bytes).decode("ascii")

    # Verify self-check before writing
    if base64.b64decode(ir_b64.encode("ascii")) != ir_bytes:
        print("error: irBase64 roundtrip mismatch", file=sys.stderr)
        sys.exit(1)

    if base64.b64decode(history_b64.encode("ascii")) != history_bytes:
        print("error: historyBase64 roundtrip mismatch", file=sys.stderr)
        sys.exit(1)

    content = f"""// SPDX-License-Identifier: AGPL-3.0-only
// Copyright (c) 2026 sol pbc
// Generated by make push-catalog; do not edit.

import Foundation

nonisolated enum PushCatalogContract {{
    static let irBase64: String = "{ir_b64}"
    static let historyBase64: String = "{history_b64}"
}}
"""

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)

    # Re-verify written file
    # Ensure written base64 decodes back to original bytes
    import re
    with open(output_path, "r", encoding="utf-8") as f:
        written = f.read()

    ir_match = re.search(r'static let irBase64: String = "([^"]+)"', written)
    hist_match = re.search(r'static let historyBase64: String = "([^"]+)"', written)
    if not ir_match or not hist_match:
        print("error: could not parse written Swift file", file=sys.stderr)
        sys.exit(1)

    if base64.b64decode(ir_match.group(1).encode("ascii")) != ir_bytes:
        print("error: written irBase64 mismatch", file=sys.stderr)
        sys.exit(1)

    if base64.b64decode(hist_match.group(1).encode("ascii")) != history_bytes:
        print("error: written historyBase64 mismatch", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()
