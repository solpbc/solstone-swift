#!/usr/bin/env python3
"""Generate Apple catalog resources and check their committed byte lock."""
import argparse,copy,hashlib,json,re,shutil,subprocess,tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent

def write(p,v):
 p.parent.mkdir(parents=True,exist_ok=True);p.write_text(json.dumps(v,indent=2,ensure_ascii=False)+'\n')
def snapshot():
 inputs=[ROOT/'Sources/AppIntents/SolstoneAppShortcuts.swift',ROOT/'scripts/i18n.py',ROOT/'i18n/compiler.json',ROOT/'i18n/targets.json']+list((ROOT/'i18n/catalog').rglob('*'))+list((ROOT/'Localization').rglob('*'))+list((ROOT/'i18n/generated').rglob('*'))
 result={str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(inputs) if p.is_file()}
 return result
def check():
 expected=json.loads((ROOT/'i18n/generated-lock.json').read_text());actual=snapshot();diff=[k for k in expected.keys()|actual.keys() if expected.get(k)!=actual.get(k)]
 if diff:raise SystemExit('Catalog or generated resources changed. Run make i18n-generate with the pinned compiler:\n'+'\n'.join(sorted(diff)))
 print('Catalog and generated resources match the committed byte lock.')
def generate(compiler,channel):
 config=json.loads((ROOT/'i18n/targets.json').read_text())
 with tempfile.TemporaryDirectory(prefix='ios-catalog-') as tmp:
  tmp=Path(tmp)
  extra=['--fallback-stale'] if channel=='development' else []
  subprocess.run([compiler,'emit',str(ROOT/'i18n/catalog'),'--channel',channel,*extra,'--out',str(tmp/'ir.json')],check=True)
  subprocess.run([compiler,'targets',str(ROOT/'i18n/catalog'),'--channel',channel,*extra,'--target','apple','--out',str(tmp/'out')],check=True)
  ir=json.loads((tmp/'ir.json').read_text());messages={m['id']:m for m in ir['messages']};xc=json.loads((tmp/'out/apple/ios.xcstrings').read_text())
  def clean(value):
   if isinstance(value,dict):
    for k,v in value.items():
     if k=='value' and isinstance(v,str):
      if '\ue000' in v or '\ue001' in v:raise ValueError('Reserved argument marker in template')
      value[k]=v.replace('\u2068','').replace('\u2069','')
     else:clean(v)
   elif isinstance(value,list):
    for v in value:clean(v)
  for entry in xc['strings'].values():clean(entry['localizations'].get('en-US',{}))
  functions=[]
  for id,m in sorted(messages.items()):
   args=json.loads((ROOT/'i18n/catalog/meta'/f'{id}.json').read_text())['arguments'];name=id.replace('.','_')
   params=', '.join('_ '+a['name']+': '+('Int' if a['type']=='cardinal' else 'String') for a in args)
   values=['Int64('+a['name']+')' if a['type']=='cardinal' else a['name'] for a in args]
   if m['format_intent']=='cardinal':
    sel=next(a for a in args if a['name']==m['selector']['name'])
    if sel.get('numeric_style')=='ungrouped':values.append('String('+sel['name']+')')
   # Enum resources carry branch-specific keys; their adapter selects the declared default.
   if m['format_intent']=='enum':raise ValueError('Generate enum adapters explicitly: '+id)
   functions.append('    static func '+name+'('+params+') -> String { render("'+m['resource']+'", ['+', '.join(values)+']) }')
   if not args:functions.append('    static func '+name+'_resource() -> LocalizedStringResource { resource("'+m['resource']+'") }')
  for style,swift in [('comma','joinedComma'),('middledot','joinedMiddleDot'),('semicolon','joinedSemicolon')]:
   arms=['        case 0: return ""','        case 1: return values[0]']
   for count in range(2,6): arms.append('        case '+str(count)+': return ios_list_'+style+'_n'+str(count)+'('+', '.join('values['+str(i)+']' for i in range(count))+')')
   arms.append('        default: return ios_list_'+style+'_n5(values[0], values[1], values[2], values[3], '+swift+'(Array(values.dropFirst(4))))')
   functions.append('    static func '+swift+'(_ values: [String]) -> String {\n        switch values.count {\n'+'\n'.join(arms)+'\n        }\n    }')
  legacy=[]
  for alias,id in config['aliases'].items():
   entry=copy.deepcopy(xc['strings'][messages[id]['resource']])
   args=json.loads((ROOT/'i18n/catalog/meta'/(id+'.json')).read_text())['arguments']
   for localization in entry['localizations'].values():
    for index,arg in enumerate(args):
     localization['stringUnit']['value']=localization['stringUnit']['value'].replace('%'+str(index+1)+'$@','{'+arg['name']+'}')
   xc['strings'][alias]=entry
   params=', '.join('values["'+a['name']+'"] ?? "{'+a['name']+'}"' for a in args)
   legacy.append('        case '+json.dumps(alias)+': return '+id.replace('.','_')+'('+params+')')
  functions.append('    static func legacy(_ key: String, values: [String: String] = [:]) -> String {\n        switch key {\n'+'\n'.join(legacy)+'\n        default: return bundle.localizedString(forKey: key, value: nil, table: "Localizable")\n        }\n    }')
  write(ROOT/'Localization/Localizable.xcstrings',xc)
  source='''// SPDX-License-Identifier: AGPL-3.0-only
// Copyright (c) 2026 sol pbc
// Generated by scripts/i18n.py from i18n/catalog. Do not edit.
import Foundation

nonisolated private final class AppCatalogBundle: NSObject {}

nonisolated enum AppStrings {
    static var bundle: Bundle { Bundle(for: AppCatalogBundle.self) }
    static var language: String { bundle.preferredLocalizations.first ?? "en-US" }
    static var locale: Locale { Locale(identifier: language) }
    static func resource(_ key: String) -> LocalizedStringResource {
        LocalizedStringResource(String.LocalizationValue(key), table: "Localizable", bundle: .atURL(bundle.bundleURL))
    }
    private static let markers = try! NSRegularExpression(pattern: "\\u{E000}catalog([0-9]+)\\u{E001}")
    static func render(_ key: String, _ arguments: [CVarArg]) -> String {
        let format = bundle.localizedString(forKey: key, value: nil, table: "Localizable")
        if language != "en-US" { return String(format: format, locale: locale, arguments: arguments) }
        var strings: [String] = []
        let neutral: [CVarArg] = arguments.map { argument in
            guard let value = argument as? String else { return argument }
            let index = strings.count
            strings.append(value)
            return "\\u{E000}catalog\\(index)\\u{E001}"
        }
        let formatted = String(format: format, locale: locale, arguments: neutral)
        let source = formatted as NSString
        let result = NSMutableString(string: formatted)
        for match in markers.matches(in: formatted, range: NSRange(location: 0, length: source.length)).reversed() {
            let index = Int(source.substring(with: match.range(at: 1)))!
            result.replaceCharacters(in: match.range, with: strings[index])
        }
        return result as String
    }
'''+'\n'.join(functions)+'\n}\n'
  (ROOT/'Localization/AppStrings.generated.swift').write_text(source)
  shortcuts=dict(sourceLanguage=xc['sourceLanguage'],version=xc['version'],strings={})
  phrase_literals=[]
  for id in config.get('shortcuts',[]):
   entry=copy.deepcopy(xc['strings'][messages[id]['resource']])
   for localization in entry['localizations'].values():
    localization['stringUnit']['value']=localization['stringUnit']['value'].replace('\u2068','').replace('\u2069','').replace('%1$@','${applicationName}').replace('%%','%')
   key=entry['localizations']['en-US']['stringUnit']['value']
   shortcuts['strings'][key]=entry
   phrase_literals.append(json.dumps(key,ensure_ascii=False).replace('${applicationName}',r'\(.applicationName)'))
  write(ROOT/'Localization/AppShortcuts.xcstrings',shortcuts)
  if phrase_literals:
   (ROOT/'Sources/AppIntents/SolstoneAppShortcuts.swift').write_text("// SPDX-License-Identifier: AGPL-3.0-only\n// Copyright (c) 2026 sol pbc\n// Generated by scripts/i18n.py from i18n/catalog. Do not edit.\nimport AppIntents\n\nstruct SolstoneAppShortcuts: AppShortcutsProvider {\n    static var shortcutTileColor: ShortcutTileColor { .orange }\n    static var appShortcuts: [AppShortcut] {\n        AppShortcut(intent: ObserverCaptureIntent(value: true), phrases: [\n" + ',\n'.join('            '+p for p in phrase_literals) + "\n        ], shortTitle: LocalizedStringResource(\"m696f732e696e74656e74732e7475726e6f6e617564696f\", table: \"Localizable\"), systemImageName: \"waveform\")\n    }\n}\n")
  # Both XcodeGen paths receive the same canonical fallback. Each bundle also gets InfoPlist.strings.
  lines=['# Generated by scripts/i18n.py from i18n/catalog. Do not edit.','options:','  developmentLanguage: en-US','settings:','  base:','    SWIFT_EMIT_LOC_STRINGS: NO','    STRING_CATALOG_GENERATE_SYMBOLS: NO','targets:']
  def yaml_value(value): return value if re.fullmatch(r'[A-Za-z0-9_-]+',value) else json.dumps(value,ensure_ascii=False)
  for target,mapping in config['info'].items():
   if not mapping:continue
   lines+=['  '+target+':','    settings:','      base:']
   values={k:xc['strings'][messages[v['id']]['resource']]['localizations']['en-US']['stringUnit']['value'].replace('%%','%') for k,v in mapping.items()}
   for k,value in values.items():lines+=['        INFOPLIST_KEY_'+k+': '+yaml_value(value)]
   lines+=['    info:','      properties:','        CFBundleDevelopmentRegion: en-US','        CFBundleLocalizations: '+json.dumps(ir['locales'])]
   for k,value in values.items():lines+=['        '+k+': '+yaml_value(value)]
   table=dict(sourceLanguage=xc['sourceLanguage'],version=xc['version'],strings={})
   for k,v in mapping.items():
    entry=copy.deepcopy(xc['strings'][messages[v['id']]['resource']])
    for loc in entry['localizations'].values():loc['stringUnit']['value']=loc['stringUnit']['value'].replace('%%','%')
    table['strings'][k]=entry
   if mapping:write(ROOT/'Localization/Metadata'/target/'InfoPlist.xcstrings',table)
  (ROOT/'i18n/generated').mkdir(exist_ok=True)
  (ROOT/'i18n/generated/project.yml').write_text('\n'.join(lines)+'\n')
  write(ROOT/'i18n/generated/locales.json',ir['locales'])
 if channel=='production':write(ROOT/'i18n/generated-lock.json',snapshot())
 print('Generated Apple resources for '+', '.join(config['info']))
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--compiler');p.add_argument('--channel',default='production');a=p.parse_args()
 if a.check:check()
 elif a.compiler:generate(str(Path(a.compiler).resolve()),a.channel)
 else:p.error('--compiler PATH required')
